"""
Bin sticker generator — SHARED CORE — Kerbside Craft Co.

Split out Sep 2026 from the original single-file bin_sticker.py so each
print size can live in its own script (bin_sticker_small.py at
140x100mm, bin_sticker_medium.py at 210x140mm, and so on) without a bug
in one size's code risking the others. This module holds everything
that's genuinely size-agnostic: icon caching, accent palettes, the base
card + border drawing, plain vector icon shapes, font-fit/curved-text
helpers, and a generic grid sheet-layout function every size script
calls with its own card size and grid shape.

What does NOT live here: any style-drawing function, any per-style
pixel-measured constant (hollow icon positions, text centre-Y values,
etc.), and the STYLES/STYLE_LABELS/STYLE_PRODUCT_ID registries — those
are inherently per-size (a style's constants were measured against one
specific card size/aspect ratio) and belong in each size script.

Import this module from a size script with:
    import bin_sticker_core as core
or:
    from bin_sticker_core import *
"""

