# Vector icon helpers — plain shapes only, no external art. Each is
# self-contained (no card-size dependency, just a `size` param), so they
# work identically at any print size.
# ---------------------------------------------------------------------------

def draw_flower_icon(c, cx, cy, size, color):
    c.saveState()
    # flanking leaves, drawn first so the flower sits on top
    c.setFillColor(HexColor(color))
    leaf_w, leaf_h = size * 0.55, size * 0.20
    for side in (-1, 1):
        c.saveState()
        c.translate(cx + side * size * 0.5, cy - size * 0.08)
        c.rotate(side * 25)
        c.ellipse(-leaf_w / 2, -leaf_h / 2, leaf_w / 2, leaf_h / 2, fill=1, stroke=0)
        c.restoreState()
    pw, ph = size * 0.35, size * 0.5
    for dx, dy in [(0, 1), (0, -1)]:
        c.ellipse(cx - pw / 2, cy + dy * size * 0.1, cx + pw / 2, cy + dy * size * 0.1 + dy * ph, fill=1, stroke=0)
    for dx, dy in [(1, 0), (-1, 0)]:
        c.ellipse(cx + dx * size * 0.1, cy - pw / 2, cx + dx * size * 0.1 + dx * ph, cy + pw / 2, fill=1, stroke=0)
    c.setFillColor(HexColor("#4A3B1D"))
    r = size * 0.13
    c.ellipse(cx - r, cy - r, cx + r, cy + r, fill=1, stroke=0)
    c.restoreState()


def draw_house_icon(c, cx, cy, size, color):
    c.saveState()
    c.setFillColor(HexColor(color))
    w, h = size * 0.8, size * 0.5
    c.rect(cx - w / 2, cy - h / 2, w, h, fill=1, stroke=0)
    p = c.beginPath()
    p.moveTo(cx - w / 2 - size * 0.08, cy + h / 2)
    p.lineTo(cx, cy + h / 2 + size * 0.32)
    p.lineTo(cx + w / 2 + size * 0.08, cy + h / 2)
    p.close()
    c.drawPath(p, fill=1, stroke=0)
    c.setFillColor(white)
    dw, dh = w * 0.22, h * 0.55
    c.rect(cx - dw / 2, cy - h / 2, dw, dh, fill=1, stroke=0)
    c.restoreState()


def draw_paw_icon(c, cx, cy, size, color):
    c.saveState()
    c.setFillColor(HexColor(color))
    c.ellipse(cx - size * 0.22, cy - size * 0.20, cx + size * 0.22, cy + size * 0.12, fill=1, stroke=0)
    toe_r = size * 0.10
    for dx, dy in [(-0.22, 0.22), (-0.08, 0.30), (0.08, 0.30), (0.22, 0.22)]:
        c.ellipse(cx + dx * size - toe_r, cy + dy * size - toe_r,
                   cx + dx * size + toe_r, cy + dy * size + toe_r, fill=1, stroke=0)
    c.restoreState()


def draw_center_flourish(c, cx, y, icon_rel_path, width, color=INK):
    """Draws a flourish as a real image asset (extracted from the
    reference PNG via icon-silhouette-extraction, then recoloured/cached
    exactly like the P02 house icon), rather than a hand-drawn or
    hand-traced vector approximation. width is the desired real-world
    width in points/mm; height is derived from the source PNG's own
    aspect ratio so it isn't stretched."""
    master = asset_path(icon_rel_path)
    if not os.path.exists(master):
        return  # asset missing -- draw nothing rather than a wrong placeholder
    name = os.path.splitext(os.path.basename(icon_rel_path))[0]
    coloured_path = cached_icon_path(f"{name}_{color.lstrip('#')}.png")
    if not os.path.exists(coloured_path):
        recolour_silhouette(master, coloured_path, color)
    img = ImageReader(coloured_path)
    iw, ih = img.getSize()
    height = width * ih / iw
    c.drawImage(img, cx - width / 2, y - height / 2, width=width, height=height, mask="auto")


# ---------------------------------------------------------------------------
# Text auto-fit and curved text -- both fully generic (no card-size
# dependency; max_width/curve_coeffs are passed in explicitly by the
# caller).
# ---------------------------------------------------------------------------

def fit_font_size(text, font, max_size, min_size, max_width, step=0.5):
    """Shrinks from max_size until `text` fits within max_width (points),
    or hits min_size."""
    size = max_size
    while size > min_size and stringWidth(text, font, size) > max_width:
        size -= step
    return round(size, 1)


# Adobe AFM CapHeight values, used to centre house-number/street-name
# text against its actual ink height rather than the font's full
# ascent+descent box (which reserves space for descenders that digit
# strings and .upper()'d street names never use, pulling a
# getAscentDescent-based centre too low). Standard published values, not
# derived per-size -- correct at any card size.
TIMES_BOLD_CAP_HEIGHT_RATIO = 0.676
HELVETICA_BOLD_CAP_HEIGHT_RATIO = 0.718


def draw_curved_text(c, text, cx, baseline, font, size, color,
                      icon_x_left, icon_scale, curve_fn, curve_coeffs):
    """Draws `text` centred on cx, following curve_fn (an icon-local-px
    -> icon-local-px function). `baseline` is where the centre character
    sits; curvature is a per-character offset relative to that, so this
    degrades gracefully to flat text if curve_fn is ~constant.

    `curve_coeffs` (a, b, c of the same quadratic curve_fn implements) is
    used ONLY for the per-character rotation angle (the fit's slope at
    that x). Passed explicitly rather than read from a module-level
    constant, so two different callers (e.g. P02's banner curve and a
    future P06-equivalent) never accidentally share rotation math."""
    total_w = stringWidth(text, font, size)
    x_cursor = cx - total_w / 2
    x_img_at_cx = (cx - icon_x_left) / (icon_scale * mm)
    ref_mid_px = curve_fn(x_img_at_cx)
    a, b, _ = curve_coeffs

    c.setFillColor(HexColor(color))
    c.setFont(font, size)
    for ch in text:
        cw = stringWidth(ch, font, size)
        x_char = x_cursor + cw / 2
        x_img = (x_char - icon_x_left) / (icon_scale * mm)
        mid_px = curve_fn(x_img)
        delta_y = -(mid_px - ref_mid_px) * icon_scale * mm  # image y-down -> reportlab y-up
        slope_img = 2 * a * x_img + b
        angle_deg = -math.degrees(math.atan(slope_img))
        c.saveState()
        c.translate(x_char, baseline + delta_y)
        c.rotate(angle_deg)
        c.drawCentredString(0, 0, ch)
        c.restoreState()
        x_cursor += cw


# ---------------------------------------------------------------------------
# Generic grid sheet layout -- the piece that makes per-size scripts
# possible without duplicating layout math. Every size script calls this
# with its OWN card_w/card_h and grid shape (cols x rows); this function
# doesn't know or care which size it's laying out.
#
# IMPORTANT ASYMMETRY THIS REPLACES: the original single-file design
# always assumed a 2x2 (4-up) grid, because every style that existed so
# far happened to fit that shape. Medium (210x140mm) breaks that
# assumption -- it's 2-per-sheet STACKED (1 col x 2 rows), not 2x2 --
# so this function takes cols/rows explicitly rather than hardcoding 2x2.
# ---------------------------------------------------------------------------

def sheet_layout(card_w, card_h, page_w, page_h, cols, rows, margin_x=None, margin_y=None):
    """Computes the grid of card bottom-left origins for a cols x rows
    grid of card_w x card_h cards on a page_w x page_h page.

    margin_x: explicit LEFT margin in points, for an asymmetric layout
    (e.g. the small size's 14mm left margin for lamination slack). If
    None, centred automatically.

    margin_y: explicit TOP margin in points (the gap above the FIRST/
    top row) -- NOT the bottom margin, despite the name possibly
    suggesting otherwise. Rows are generated top-row-first to match the
    "top-left, top-right, ..." position ordering documented below, so
    margin_y anchors that same top edge. If None, centred automatically.
    Confirmed directly (Sep 2026): margin_y=14mm on a 2-row layout with
    17mm total slack produces a 14mm gap above the top row and a 3mm gap
    below the bottom row, not the reverse.

    Positions are returned top-row-first, left-to-right (matching the
    original single-file convention: top-left, top-right, ..., bottom-
    left, bottom-right)."""
    total_w = cols * card_w
    total_h = rows * card_h
    if margin_x is None:
        margin_x = (page_w - total_w) / 2
    else:
        available = page_w - total_w
        assert margin_x <= available, (
            f"margin_x ({margin_x / mm}mm) exceeds the {available / mm}mm of "
            f"horizontal slack available for a {cols}x{rows} grid of "
            f"{card_w / mm}x{card_h / mm}mm cards on a {page_w / mm}mm-wide "
            f"page -- reduce margin_x or this grid can't fit at this size."
        )
    if margin_y is None:
        margin_y = (page_h - total_h) / 2
    else:
        available_y = page_h - total_h
        assert margin_y <= available_y, (
            f"margin_y ({margin_y / mm}mm) exceeds the {available_y / mm}mm of "
            f"vertical slack available for a {cols}x{rows} grid of "
            f"{card_w / mm}x{card_h / mm}mm cards on a {page_h / mm}mm-tall "
            f"page -- reduce margin_y or this grid can't fit at this size."
        )
    positions = []
    for r in range(rows):
        y = page_h - margin_y - card_h - r * card_h
        for col in range(cols):
            x = margin_x + col * card_w
            positions.append((x, y))
    return margin_x, margin_y, positions


def render_sheet_grid(orders, out_path, card_w, card_h, cols, rows, draw_fn,
                       page_size, margin_x=None, margin_y=None, caption=False,
                       style_labels=None):
    """Renders up to cols*rows cards in a grid on one page.

    draw_fn(c, ox, oy, order): draws one card at the given origin --
    normally a size script's own draw_sticker.
    page_size: explicit (w, h) in points. Deliberately NOT auto-derived
    from card_w/card_h here (a card being wider than tall does NOT mean
    its SHEET should be landscape -- Medium's 210x140mm card sits on a
    PORTRAIT page, stacked vertically, which is exactly the case that
    would break an auto "landscape if card_w > card_h" heuristic). Each
    size script passes its own real page orientation explicitly.
    style_labels: optional dict for the `caption=True` bottom-margin
    label (order["style"] -> display string); falls back to the raw key.
    """
    if len(orders) > cols * rows:
        raise ValueError(
            f"render_sheet_grid got {len(orders)} orders but the {cols}x{rows} "
            f"grid only holds {cols * rows} -- split into multiple calls."
        )
    page_w, page_h = page_size
    _, _, positions = sheet_layout(card_w, card_h, page_w, page_h, cols, rows, margin_x, margin_y)

    c = canvas.Canvas(out_path, pagesize=page_size)
    for order, (x, y) in zip(orders, positions):
        draw_fn(c, x, y, order)
        if caption and "style" in order:
            c.setFont("Helvetica", 6)
            c.setFillColor(HexColor("#888888"))
            label = (style_labels or {}).get(order["style"], order["style"])
            c.drawCentredString(x + card_w / 2, 2.5 * mm, label)
    c.showPage()
    c.save()


def render_gallery_grid(style_keys, sample_order, out_path, card_w, card_h, cols, rows,
                         draw_fn, page_size, style_labels=None,
                         margin_x=None, margin_y=None):
    """One card per style in style_keys, paginated cols*rows-up.
    draw_fn(c, ox, oy, order) draws one card; order['style'] is set per
    call from style_keys. See render_sheet_grid for why page_size is
    required rather than auto-derived.

    margin_x/margin_y are forwarded to sheet_layout so a size script can
    keep the same asymmetric print margins on galleries as on sheets
    (e.g. Small's 14mm left). Default None still centres the grid."""
    page_w, page_h = page_size
    _, _, positions = sheet_layout(
        card_w, card_h, page_w, page_h, cols, rows, margin_x, margin_y,
    )
    per_page = cols * rows

    c = canvas.Canvas(out_path, pagesize=page_size)
    for i, style in enumerate(style_keys):
        slot = i % per_page
        if i > 0 and slot == 0:
            c.showPage()
        x, y = positions[slot]
        order = dict(sample_order)
        order["style"] = style
        draw_fn(c, x, y, order)
        c.setFont("Helvetica", 6)
        c.setFillColor(HexColor("#888888"))
        label = (style_labels or {}).get(style, style)
        c.drawCentredString(x + card_w / 2, 2.5 * mm, label)
    c.showPage()
    c.save()


# ---------------------------------------------------------------------------
# Cricut placement-reference SVG -- OPTIONAL, never part of a real print
# job. Purpose: a visual aid loaded into Design Space to help position
# real vector cut shapes by eye against a picture of the actual printed
# sheet, since cut-only mode has no camera/registration to do this
# automatically (see chat history, "Custom bin sticker sheet layout
# specifications" follow-up, for the full story of why this exists and
# the several rounds of correction that arrived at this design).
#
# 4 layers, each a distinct colour -- Design Space automatically splits
# an imported multi-colour SVG into one layer per colour on import, so
# no special grouping syntax is needed beyond genuinely using 4 colours:
#   GREEN  -- the full physical page boundary (sharp corners -- it's the
#             page itself, not a sticker)
#   GREY   -- each card's true edge (sharp corners) + corner tick marks,
#             matching draw_base's own convention exactly
#   BLACK  -- each card's REAL accent-border outline, at that specific
#             style's own true pad + radius (NOT a generic guess --
#             computed from the same values that style's own
#             draw_border call actually uses, via style_pad_radius)
#   RED    -- kiss-cut reference, per card, fixed 1mm inset from the true
#             edge (grey) -- guaranteed to sit outside every style's own
#             border since 1mm is less than the smallest real pad (2mm),
#             confirmed directly rather than assumed
#
# Deliberately LINES ONLY -- no illustrated design content (icons, house
# numbers, street names). This is a placement aid, not something meant
# to preview the finished design, and the full illustrated content would
# be far more complex to convert to clean SVG for no real benefit here.
#
# UNITS: unitless coordinates (1 user unit = 1px @ 96dpi) -- the SVG
# spec's own default, chosen after DIRECT TESTING found explicit "mm"
# unit suffixes import at an unpredictable wrong scale in Design Space
# (confirmed: one file imported ~2.77x too large with "mm" suffixes).
# Unitless coordinates fared better in practice but were STILL observed
# to import at an unpredictable wrong scale once (~1.3x too large) on a
# separate file -- ALWAYS verify the imported size in Design Space's own
# Size panel after upload (should read the true page size, e.g. 29.7 x
# 21.0cm for Small) and manually correct via the aspect-locked Size
# field if it's off. This isn't a one-time fix, it's a check to make
# every time -- Design Space's import scale has not been reliable.
# ---------------------------------------------------------------------------

_MM_TO_PX = 96 / 25.4  # SVG spec default: 1 user unit = 1px = 1/96 inch


def _svg_px(v_points):
    """Convert an internal reportlab-points value (i.e. anything already
    multiplied by the `mm` scale factor, like every other measurement in
    this codebase) to the unitless SVG coordinate this file uses."""
    return round((v_points / mm) * _MM_TO_PX, 3)


def render_cricut_reference_svg(orders, out_path, card_w, card_h, cols, rows,
                                 page_size, style_pad_radius,
                                 margin_x=None, margin_y=None,
                                 kiss_cut_inset=1 * mm, tick=3 * mm):
    """Writes an SVG placement-reference image (see module comment above
    for the full rationale) -- NOT a PDF, never for real cutting.

    orders: list of order dicts, one per card actually on this sheet
    (must each have a "style" key) -- NOT necessarily all styles this
    size supports, just whichever ones this specific reference is for.
    Uses the same sheet_layout positions render_sheet_grid would for
    these same cols/rows/margins, so it matches a real print exactly.

    style_pad_radius: dict, style_key -> (pad, radius) or None.
    "pad"/"radius" must be THAT STYLE'S OWN real accent-border values
    (not a generic default) -- computed once per size script from each
    style's actual _draw_border call, so the black reference line
    genuinely matches what prints, not a guess. None means this style
    has no real border (e.g. p09a_borderless, or a style like p25b
    whose border is too structurally different from a simple rounded
    rectangle to represent this way) -- the black layer is simply
    skipped for that specific card; grey and red still render as usual.
    """
    if len(orders) > cols * rows:
        raise ValueError(
            f"render_cricut_reference_svg got {len(orders)} orders but the "
            f"{cols}x{rows} grid only holds {cols * rows}."
        )
    page_w, page_h = page_size
    _, _, positions = sheet_layout(card_w, card_h, page_w, page_h, cols, rows, margin_x, margin_y)

    def rect_el(x, y, w, h):
        return (f'<rect x="{_svg_px(x)}" y="{_svg_px(y)}" width="{_svg_px(w)}" '
                f'height="{_svg_px(h)}" fill="none" stroke-width="1.5" />')

    def roundrect_el(x, y, w, h, r):
        return (f'<rect x="{_svg_px(x)}" y="{_svg_px(y)}" width="{_svg_px(w)}" '
                f'height="{_svg_px(h)}" rx="{_svg_px(r)}" ry="{_svg_px(r)}" '
                f'fill="none" stroke-width="1.5" />')

    green_shapes = [rect_el(0, 0, page_w, page_h)]

    grey_shapes = []
    black_shapes = []
    red_shapes = []
    for order, (x_rl, y_rl) in zip(orders, positions):
        # Flip bottom-left/y-up (reportlab, matches every other position
        # in this codebase) to top-left/y-down (SVG) -- same flip as the
        # already-confirmed working small_cut_lines.svg.
        x = x_rl
        y = page_h - y_rl - card_h

        grey_shapes.append(rect_el(x, y, card_w, card_h))
        for cx, cy, dx, dy in [
            (x, y, -tick, -tick), (x + card_w, y, tick, -tick),
            (x, y + card_h, -tick, tick), (x + card_w, y + card_h, tick, tick),
        ]:
            grey_shapes.append(f'<line x1="{_svg_px(cx)}" y1="{_svg_px(cy)}" '
                                f'x2="{_svg_px(cx + dx)}" y2="{_svg_px(cy)}" stroke-width="1.5" />')
            grey_shapes.append(f'<line x1="{_svg_px(cx)}" y1="{_svg_px(cy)}" '
                                f'x2="{_svg_px(cx)}" y2="{_svg_px(cy + dy)}" stroke-width="1.5" />')

        style = order["style"]
        pad_radius = style_pad_radius.get(style)
        if pad_radius is not None:
            pad, radius = pad_radius
            black_shapes.append(roundrect_el(x + pad, y + pad, card_w - 2 * pad, card_h - 2 * pad, radius))

        i = kiss_cut_inset
        # Use this style's own radius for red too if known, otherwise a
        # plain rectangle (0 radius) -- red should still visually relate
        # to the same corner style as black where that's known.
        red_radius = pad_radius[1] if pad_radius is not None else 0
        red_shapes.append(roundrect_el(x + i, y + i, card_w - 2 * i, card_h - 2 * i, red_radius))

    svg = (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{_svg_px(page_w)}" height="{_svg_px(page_h)}"\n'
        f'     viewBox="0 0 {_svg_px(page_w)} {_svg_px(page_h)}">\n'
        f'  <g id="green_page_frame" stroke="#00A651">\n    ' + "\n    ".join(green_shapes) + "\n  </g>\n"
        f'  <g id="grey_cut_guide" stroke="#CCCCCC">\n    ' + "\n    ".join(grey_shapes) + "\n  </g>\n"
        f'  <g id="black_accent_border" stroke="#111111">\n    ' + ("\n    ".join(black_shapes) if black_shapes else "") + "\n  </g>\n"
        f'  <g id="red_kiss_cut" stroke="#E8112D">\n    ' + "\n    ".join(red_shapes) + "\n  </g>\n"
        "</svg>\n"
    )
    with open(out_path, "w") as f:
        f.write(svg)
