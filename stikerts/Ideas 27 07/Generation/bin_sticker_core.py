# ---------------------------------------------------------------------------
# Asset path resolution — resolved relative to THIS file's location, not
# whichever size script happens to be __main__. Every size script lives
# alongside this one and shares the same assets/ folder (recolouring is
# size-independent — the same master PNG gets drawn at whatever mm width
# a style requests at render time, so there's no need for a separate
# assets/ copy per size).
# ---------------------------------------------------------------------------
_SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))


def asset_path(rel_path):
    return os.path.join(_SCRIPT_DIR, rel_path)


# ---------------------------------------------------------------------------
# Recoloured per-accent icon cache. Written to a fresh OS temp directory,
# created lazily and cleaned up automatically at process exit (atexit) --
# NOT cached permanently in assets/icons/, because a permanent cache only
# ever asks "does this file exist", never "is it still correct", which
# let a stale wrong-colour file survive a later code fix (real bug, Aug
# 2026). Shared across every size script that imports this module: since
# recolouring is size-independent, a "house_banner_navy.png" generated by
# bin_sticker_small.py can be safely reused if bin_sticker_medium.py asks
# for the exact same master + colour, rather than re-running the recolour
# loop twice for identical output.
# ---------------------------------------------------------------------------
_ICON_CACHE_DIR = None


def get_icon_cache_dir():
    global _ICON_CACHE_DIR
    if _ICON_CACHE_DIR is None:
        _ICON_CACHE_DIR = tempfile.mkdtemp(prefix="bin_sticker_icons_")
        atexit.register(shutil.rmtree, _ICON_CACHE_DIR, ignore_errors=True)
    return _ICON_CACHE_DIR


def cached_icon_path(name):
    """Path for a recoloured icon variant inside this run's temp cache
    (e.g. name='house_banner_black.png'). Distinct from asset_path, which
    resolves permanent, real source assets."""
    return os.path.join(get_icon_cache_dir(), name)


def recolour_silhouette(in_path, out_path, hex_color):
    """Recolours a single-colour silhouette PNG to any hex value, using
    its own alpha channel as the mask (so anti-aliased edges stay clean)."""
    img = Image.open(in_path).convert("RGBA")
    r, g, b = tuple(int(hex_color.lstrip("#")[i:i + 2], 16) for i in (0, 2, 4))
    pixels = img.load()
    for y in range(img.height):
        for x in range(img.width):
            _, _, _, a = pixels[x, y]
            if a > 0:
                pixels[x, y] = (r, g, b, a)
    img.save(out_path)


# ---------------------------------------------------------------------------
# Colours
# ---------------------------------------------------------------------------
BG = "#FFFFFF"
INK = "#111111"
INK_MUTED = "#555555"
GUIDE = "#CCCCCC"
PAD = 2 * mm  # inset of the design/border from the cut edge, shared default
BORDER_CORNER_RADIUS = 7 * mm  # rounded-corner radius for draw_border's
# accent-colour printed border (Sep 2026, revised) -- matches the middle
# option of the physical 3-in-1 corner rounder punch (4mm/7mm/10mm), NOT
# the original 2mm chosen from a pure visual-preference test. That 2mm
# choice was made before checking the punch tool's actual fixed radii --
# 2mm isn't achievable with any real punch option, so the software
# border now matches a size the physical tool can actually produce.
# 7mm chosen as the middle ground given unresolved prior test data
# (Material-Test-Plan.md, Aug 2026, Stickiply material only): 4mm/7mm
# jammed the punch, 10mm avoided jamming but tore the material -- 7mm
# splits the difference between the two reported failure modes rather
# than being a confirmed-safe choice. Re-test on real Cricut-brand
# material before committing to bulk production.
#
# NOT the grey cut-guide line in draw_base, which stays sharp-cornered
# on purpose (it's a cutting reference, not part of the finished
# design). See draw_border's own docstring for which styles this does
# and doesn't apply to.

ACCENTS = {
    "black":      INK,
    "charcoal":   "#2C2C2A",
    "forest":     "#2F5233",
    "navy":       "#1F3A5F",
    "terracotta": "#B0532E",
    "berry":      "#7A2E4D",
    "mustard":    "#B4841F",
}

# Second palette for a different production method: printing coloured ink
# on CLEAR vinyl and applying direct to a coloured bin, no white card
# behind it (Technique F in Idea-Board-Solutions-Reference.md). These 5
# were chosen for visibility on dark bin plastic (green/brown deliberately
# avoided so they don't blend into 2 of the 3 most common bin colours) --
# they are NOT a stylistic alternative to ACCENTS, they solve a different
# problem (opacity on clear film) and are picked for that, not for how
# they look on a white card.
#
# STATUS: not yet production-validated. Bin-Sticker-Material-Test-Plan.md
# Addendum 2 (visibility on black/green/brown) and Addendum 3 (UV/scratch
# durability on clear film specifically) are both still pending physical
# testing as of this palette being added to the script.
CLEAR_VINYL_ACCENTS = {
    "golden_yellow": "#F2B705",
    "cream":         "#F5E8C8",
    "burnt_amber":   "#D9782E",
    "powder_blue":   "#8FB8DE",
    "dusty_rose":    "#E08A73",
}


def resolve_accent(accent_key, default="navy"):
    """Looks up an accent key in ACCENTS first, then CLEAR_VINYL_ACCENTS,
    so any style function can accept a key from either palette. Falls
    back to ACCENTS[default] if the key isn't found in either."""
    if accent_key in ACCENTS:
        return ACCENTS[accent_key]
    if accent_key in CLEAR_VINYL_ACCENTS:
        return CLEAR_VINYL_ACCENTS[accent_key]
    return ACCENTS[default]


# ---------------------------------------------------------------------------
# Shared icon-asset registry -- "floral", "house", "paw" only. These 3
# vector fallbacks (and their matching illustrated-art upgrade paths) are
# used across multiple styles in multiple size scripts (the wreath
# family, house_banner/p27/p47, and the duck/dog/cat families +
# p21_paw_trail respectively), so they live here rather than being
# duplicated per size script. A style-specific illustrated asset (e.g.
# house_banner_master.png, p21_paw_trail_icon.png) is NOT a generic
# fallback and stays defined in its own size script instead.
# ---------------------------------------------------------------------------
ICON_ASSETS = {
    "floral": "assets/icons/flower_icon.png",
    "house": "assets/icons/house_icon.png",
    "paw": "assets/icons/paw_icon.png",
}


def draw_icon(c, cx, cy, size, color, style_key, vector_fn):
    """Use the illustrated PNG in ICON_ASSETS if it exists on disk,
    otherwise fall back to the built-in vector shape. This is the single
    switchover point — once real artwork lands at the path above, every
    sticker using that style upgrades automatically."""
    rel_path = ICON_ASSETS.get(style_key)
    if rel_path and os.path.exists(asset_path(rel_path)):
        img = ImageReader(asset_path(rel_path))
        c.drawImage(img, cx - size / 2, cy - size / 2, size, size,
                    mask='auto', preserveAspectRatio=True)
    else:
        vector_fn(c, cx, cy, size, color)


# ---------------------------------------------------------------------------
# Base layer (every sticker) and border layer (drawn LAST so colour-block
# styles never paint over it). w/h are REQUIRED (no default card size) --
# this module doesn't know which size script is calling it, so a size
# script that forgets to pass its own w/h should get a loud TypeError,
# not a silent wrong-sized card.
# ---------------------------------------------------------------------------

def draw_base(c, ox, oy, w, h):
    c.setFillColor(HexColor(BG))
    c.rect(ox, oy, w, h, fill=1, stroke=0)

    c.setStrokeColor(HexColor(GUIDE))
    c.setLineWidth(0.4)
    c.rect(ox, oy, w, h, fill=0, stroke=1)

    tick = 3 * mm
    for cx, cy, dx, dy in [
        (ox, oy, -tick, -tick), (ox + w, oy, tick, -tick),
        (ox, oy + h, -tick, tick), (ox + w, oy + h, tick, tick),
    ]:
        c.line(cx, cy, cx + dx, cy)
        c.line(cx, cy, cx, cy + dy)


# Colour deliberately distinct from GUIDE (the real, precise cut line) so
# the two are never confused when hand-trimming by eye -- GUIDE is what
# the Cricut/scissors should ultimately follow exactly; this is the
# looser, "cut somewhere out here" line.
TRIM_MARGIN_GUIDE_COLOR = "#4A90D9"


def draw_trim_margin_guide(c, ox, oy, w, h, margin):
    """Optional, opt-in guide for the "hand-trim into separate pieces,
    then cut precisely on the Cricut" paper-test workflow (Sep 2026) --
    draws a dashed rectangle OUTSET from the card's true boundary by
    `margin`, well outside the real cut line drawn by draw_base above.

    This is deliberately a SEPARATE function, not folded into draw_base,
    and deliberately not called by default anywhere -- it only exists to
    mark where it's safe to hand-trim with scissors/guillotine BEFORE
    the precise machine cut, leaving real margin for placement error on
    the mat. It has no role in the finished product and should never
    appear on a real customer order.

    margin: how far OUTSIDE the true card edge to draw this line, e.g.
    2.5*mm for a 2.5mm trim allowance each side."""
    c.setStrokeColor(HexColor(TRIM_MARGIN_GUIDE_COLOR))
    c.setLineWidth(0.4)
    c.setDash(2, 2)
    c.rect(ox - margin, oy - margin, w + 2 * margin, h + 2 * margin, fill=0, stroke=1)
    c.setDash()


def draw_border(c, ox, oy, order, weight="single", *, w, h, pad=None):
    """pad overrides the shared PAD cutting-tolerance inset for this call
    only -- used when one style needs a different cut-to-border margin
    than the rest. Defaults to the shared PAD if not given.

    w/h are keyword-only and required (no default) -- every real call
    site already passes them as w=.../h=... keywords (a holdover from
    the original single-file signature, where they had defaults), so
    keyword-only here doesn't break any call site, it just makes the
    lack of a default explicit and stops `weight`'s position from ever
    colliding with a keyword `w=` the way a plain positional w would.

    Corners are rounded at BORDER_CORNER_RADIUS (7mm as of Sep 2026,
    matching the middle option on the physical 3-in-1 corner punch --
    see the constant's own comment). This does NOT touch every style's
    border -- p09a_borderless has no border at all by design, and
    p25b's corner-bracket artwork is bespoke and doesn't use a radius
    concept at all. p25_landscape_flourish draws its own thicker
    roundRect rather than calling this function, but uses the same
    7mm punch radius via P25_BORDER_RADIUS. Every other bordered
    style goes through this function and picks up the 7mm rounding
    automatically."""
    if pad is None:
        pad = PAD
    accent = HexColor(resolve_accent(order.get("accent", "charcoal")))
    c.setStrokeColor(accent)
    c.setLineWidth(1.1)
    c.setDash()
    c.roundRect(ox + pad, oy + pad, w - 2 * pad, h - 2 * pad, BORDER_CORNER_RADIUS, fill=0, stroke=1)
    if weight == "double":
        c.setLineWidth(0.5)
        inset = pad + 2.2 * mm
        c.roundRect(ox + inset, oy + inset, w - 2 * inset, h - 2 * inset, BORDER_CORNER_RADIUS, fill=0, stroke=1)
    elif weight == "dashed":
        c.setDash(2, 2)
        c.setLineWidth(0.7)
        inset = pad + 2.0 * mm
        c.roundRect(ox + inset, oy + inset, w - 2 * inset, h - 2 * inset, BORDER_CORNER_RADIUS, fill=0, stroke=1)
        c.setDash()


